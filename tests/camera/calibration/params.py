"""Where calibration files live, and how they are saved and loaded.

Files are plain YAML (not OpenCV FileStorage) so any module can read them
with PyYAML. One file per camera + resolution: params/<calib_key>.yaml
"""

from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import yaml

CALIB_DIR = Path(__file__).resolve().parent
IMAGES_DIR = CALIB_DIR / "images"
PARAMS_DIR = CALIB_DIR / "params"


class CalibrationNotFound(FileNotFoundError):
    """No calibration file exists for this camera + resolution."""


def params_path(calib_key):
    return PARAMS_DIR / f"{calib_key}.yaml"


def images_dir(calib_key):
    return IMAGES_DIR / calib_key


@dataclass
class Calibration:
    calib_key: str
    image_size: tuple            # (width, height)
    camera_matrix: np.ndarray    # 3x3
    dist_coeffs: np.ndarray      # 1xN
    rms_px: float
    meta: dict = field(default_factory=dict)


def save_calibration(calib_key, image_size, camera_matrix, dist_coeffs, rms_px, meta):
    PARAMS_DIR.mkdir(parents=True, exist_ok=True)
    data = {
        "calib_key": calib_key,
        "image_size": [int(image_size[0]), int(image_size[1])],
        "rms_px": round(float(rms_px), 4),
        "camera_matrix": np.asarray(camera_matrix, float).round(6).tolist(),
        "dist_coeffs": np.asarray(dist_coeffs, float).ravel().round(8).tolist(),
        **meta,
    }
    path = params_path(calib_key)
    with open(path, "w") as f:
        f.write("# Camera calibration - generated by calibration/calibrate.py. Do not edit by hand.\n")
        yaml.safe_dump(data, f, sort_keys=False, default_flow_style=None, width=100)
    return path


def load_calibration(calib_key):
    """Load params/<calib_key>.yaml. Raises CalibrationNotFound if missing."""
    path = params_path(calib_key)
    if not path.exists():
        raise CalibrationNotFound(
            f"no calibration for '{calib_key}' ({path}). "
            f"Run: python3 -m calibration.capture, then python3 -m calibration.calibrate")
    with open(path) as f:
        data = yaml.safe_load(f)
    known = {"calib_key", "image_size", "camera_matrix", "dist_coeffs", "rms_px"}
    return Calibration(
        calib_key=data["calib_key"],
        image_size=tuple(data["image_size"]),
        camera_matrix=np.array(data["camera_matrix"], dtype=np.float64),
        dist_coeffs=np.array(data["dist_coeffs"], dtype=np.float64).reshape(1, -1),
        rms_px=float(data["rms_px"]),
        meta={k: v for k, v in data.items() if k not in known},
    )
